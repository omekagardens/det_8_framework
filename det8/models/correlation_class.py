# ── Global record extendability (DET candidate principle, operational form) ──


def global_record_extendability() -> dict:
    """Test whether the Bell-state level-1 Γ extends to a PSD level-2 Γ².

    "Global record extendability" (𝔇_n = Marginal(𝔇_{n+1})) is made concrete
    as: the level-1 moment matrix must be the principal submatrix of a PSD
    level-2 moment matrix (NPA level 2). The Bell state passes (it is quantum,
    so it extends to every level); the PR box already fails level 1.
    """
    obs, psi = _bell_observables()
    w1 = _level1_words()
    w2 = _level2_words()
    G1 = _moment_matrix(w1, obs, psi)
    G2 = _moment_matrix(w2, obs, psi)
    # Level-1 words sit at level-2 indices 0..4 and 9..12.
    l2_index = {w: i for i, w in enumerate(w2)}
    principal_ok = all(
        abs(G1[i][j] - G2[l2_index[w1[i]]][l2_index[w1[j]]]) < 1e-9
        for i in range(len(w1)) for j in range(len(w1))
    )
    return {
        "level1_psd": _is_psd(G1),
        "level2_psd": _is_psd(G2),
        "level1_is_principal_submatrix": principal_ok,
        "level2_min_eigenvalue": min(_jacobi_eigh_real(G2)),
        "extends": _is_psd(G2) and principal_ok,
        "note": (
            "Bell state extends (quantum ⇒ all NPA levels). PR box fails at "
            "level 1 (S=4>2√2). Whether extendability forces Q̃ → Q is the "
            "open DET conjecture."
        ),
    }


